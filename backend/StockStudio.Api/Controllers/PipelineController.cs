    /// <summary>
    /// Quel che serve al browser per accedere a SharePoint e per accorgersi se non lo è.
    ///
    /// Le anteprime non passano più dall'API: il tag &lt;img&gt; le chiede a SharePoint con la
    /// sessione di chi guarda. Ottimo per il consumo di CPU, ma introduce un modo di fallire che
    /// prima non esisteva -- senza sessione ogni miniatura diventa un riquadro vuoto, e nulla nella
    /// pagina spiega perché. Peggio: sembra un difetto dell'applicazione.
    ///
    /// Qui si restituisce l'indirizzo del sito (dove mandare l'utente ad accedere) e l'indirizzo di
    /// una miniatura vera (con cui provare se la sessione c'è). La prova deve essere un file
    /// protetto: le risorse statiche di _layouts rispondono anche senza sessione e direbbero di sì
    /// sempre.
    /// </summary>
    [HttpGet("sessione-sharepoint")]
    public IActionResult SessioneSharePoint([FromQuery] bool nuova = false)
    {
        if (string.IsNullOrWhiteSpace(_s.SiteUrl))
            return Ok(new { ok = false, error = "SharePoint non configurato." });

        var host = new Uri(_s.SiteUrl).GetLeftPart(UriPartial.Authority);

        string? prova;
        lock (SerraturaProva)
        {
            // `nuova` serve a chi ha appena visto fallire la prova: un bersaglio che non si disegna
            // resterebbe in cache un'ora, e per un'ora l'applicazione chiederebbe un accesso che
            // non serve. Chi scopre il guasto puo' chiedere un altro bersaglio invece di subirlo.
            if (!nuova && _provaUrl != null && DateTimeOffset.UtcNow - _provaQuando < TimeSpan.FromHours(1))
                prova = _provaUrl;
            else
            {
                // Chiedere un bersaglio nuovo senza ricordare quello bocciato non servirebbe:
                // la ricerca e' deterministica e ripescherebbe lo stesso file.
                if (nuova && _provaUrl != null) _provaScartate.Add(_provaUrl);
                prova = CercaUnaMiniatura();
                if (prova != null) { _provaUrl = prova; _provaQuando = DateTimeOffset.UtcNow; }
            }
        }

        return Ok(new
        {
            ok = true,
            siteUrl = _s.SiteUrl,
            host,
            // Il punto di accesso di SharePoint: dopo l'autenticazione rimanda al sito, e i cookie
            // restano validi per tutto il dominio -- comprese le miniature.
            loginUrl = $"{_s.SiteUrl.TrimEnd('/')}/_layouts/15/Authenticate.aspx?Source={Uri.EscapeDataString(_s.SiteUrl)}",
            provaUrl = prova,
            diagnosi = _diagnosiProva,
        });
    }

    private static string? _provaUrl;
    private static DateTimeOffset _provaQuando;
    /// <summary>I bersagli che si sono gia' rivelati indisegnabili: non si ripropongono.</summary>
    private static readonly HashSet<string> _provaScartate = new(StringComparer.OrdinalIgnoreCase);
    private static readonly object SerraturaProva = new();

    /// <summary>
    /// Una miniatura qualsiasi che esista davvero. Costa una lettura da una riga, e vale un'ora:
    /// serve solo come bersaglio della prova, non come dato.
    ///
    /// Dev'essere un **raster**. Le librerie non contengono piu' soltanto JPEG: ci sono gli EPS e
    /// gli SVG delle consegne, e le cartelle dei gruppi. Di quelli getpreview.ashx non sa disegnare
    /// niente e risponde errore -- e la prova, che legge proprio quell'errore, concluderebbe
    /// "sessione assente" con la sessione perfettamente valida. Da li' l'applicazione chiede un
    /// accesso che non serve, e la finestra non si chiude mai perche' aspetta un esito che non puo'
    /// arrivare. Pescare il primo elemento qualunque esso sia bastava finche' in cima c'era un
    /// JPEG: era vero per caso, non per costruzione.
    /// </summary>
    private string? CercaUnaMiniatura()
    {
        // La lista degli scartati e' una preferenza, non un vincolo: se rispettandola non si trova
        // niente si ripesca comunque. Un bersaglio sospetto e' pur sempre meglio di nessun
        // bersaglio, perche' senza la prova non puo' nemmeno partire e lo stato resta ignoto.
        return TrovaMiniatura(true) ?? TrovaMiniatura(false);
    }

    /// <summary>Perche' la ricerca del bersaglio e' andata come e' andata: si legge da fuori.</summary>
    private static string _diagnosiProva = "";

    private string? TrovaMiniatura(bool rispettaScarti)
    {
        var righe = new List<string>();
        foreach (var libreria in new[] { "ImagesSent", "ImagesToSend", "ImagesToClassify" })
        {
            try
            {
                var page = _sp.ListItems(libreria, 60, null, null, null);
                var raster = 0;
                foreach (var i in page.Items)
                {
                    if (!DisegnabileDaSharePoint(i.ServerRelativeUrl)) continue;
                    raster++;
                    var url = UrlSharePoint.Miniatura(_s.SiteUrl!, i.ServerRelativeUrl);
                    if (rispettaScarti && _provaScartate.Contains(url)) continue;
                    righe.Add($"{libreria}: {page.Items.Count} elementi, {raster} raster, scelto");
                    _diagnosiProva = string.Join(" | ", righe);
                    return url;
                }
                righe.Add($"{libreria}: {page.Items.Count} elementi, {raster} raster, nessuno utile");
            }
            catch (Exception ex)
            {
                righe.Add($"{libreria}: {ex.GetType().Name} {ex.Message}");
            }
        }
        _diagnosiProva = string.Join(" | ", righe);
        return null;
    }

    /// <summary>I formati di cui SharePoint sa produrre una miniatura.</summary>
    private static bool DisegnabileDaSharePoint(string? serverRelativeUrl)
    {
        if (string.IsNullOrWhiteSpace(serverRelativeUrl)) return false;
        var punto = serverRelativeUrl!.LastIndexOf('.');
        if (punto < 0 || punto == serverRelativeUrl.Length - 1) return false;
        var estensione = serverRelativeUrl.Substring(punto + 1).ToLowerInvariant();
        return estensione is "jpg" or "jpeg" or "png" or "gif" or "bmp" or "webp";
    }

    /// <summary>Read-only: pipeline funnel — item counts across the ImagesToClassify → ImagesToSend → ImagesSent stages.</summary>
    [HttpGet("funnel")]
    public IActionResult Funnel()
    {
        if (!_s.Enabled) return BadRequest("Pipeline disabilitata.");
        try
        {
            var libs = _sp.ListDocumentLibraries();
            int CountOf(string name)
            {
                foreach (var o in libs)
                {
                    var t = o.GetType();
                    var title = t.GetProperty("title")?.GetValue(o) as string;
                    if (string.Equals(title, name, StringComparison.OrdinalIgnoreCase))
                        return Convert.ToInt32(t.GetProperty("itemCount")?.GetValue(o) ?? 0);
                }
                return 0;
            }

            var stages = new[]
            {
                new { key = "classify", label = "In attesa AI (ImagesToClassify)", count = CountOf("ImagesToClassify") },
                new { key = "send", label = "Post-AI, pre-invio (ImagesToSend)", count = CountOf("ImagesToSend") },
                new { key = "sent", label = "Pubblicati (ImagesSent)", count = CountOf("ImagesSent") },
            };
            return Ok(new { ok = true, stages, timestamp = DateTime.UtcNow.ToString("o") });
        }
        catch (Exception ex) { return Ok(new { ok = false, error = ex.Message }); }
    }

